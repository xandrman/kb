<?php

namespace App\Neuron;

use App\Observability\TraceHttpRequests;
use NeuronAI\Agent\Agent;
use NeuronAI\Providers\AIProviderInterface;
use NeuronAI\Providers\OpenAILike;

/**
 * LLM-as-a-Judge for the answers of the knowledge base (SRS 8.6): grounding in the fragments, completeness, sources.
 *
 * Судья — та же модель, что отвечает (ADR-0009): другой в закрытом контуре нет, самооценка — известное смещение метода.
 */
class AnswerJudge extends Agent
{
    /**
     * vLLM ограничивает вывод схемой, но описаний полей модель не видит: смысл полей — в тексте задания.
     */
    public const string ANSWER_TASK = <<<'TASK'
        Оцени ответ ассистента и верни JSON с полями:
        - unsupported — утверждения ответа, которых нет во фрагментах, кратко через точку с запятой; пустая строка, если все утверждения есть во фрагментах;
        - faithfulness — опора на фрагменты, целое от 1 до 5: 5 — каждое утверждение прямо подтверждено фрагментами; 4 — подтверждено всё существенное, есть мелкие неточности формулировок; 3 — есть существенные утверждения без опоры; 2 — большая часть ответа без опоры; 1 — ответ не следует из фрагментов или противоречит им;
        - completeness — полнота, целое от 1 до 5: 5 — ответ на все части вопроса; 4 — ответ на все части, но без важной детали; 3 — нет ответа на одну из частей вопроса; 2 — ответ лишь на малую часть; 1 — ответ не на вопрос;
        - citesSources — true, если ответ называет, откуда сведения: документ, паспорт, руководство, акт с номером; иначе false.
        TASK;

    public const string REFUSAL_TASK = <<<'TASK'
        Ассистент отказался отвечать. Верни JSON с полями:
        - evidence — выпиши сведения из фрагментов, которые отвечают на вопрос, и для каждого — к какому изделию, модели или серии он относится по фрагменту; пустая строка, если таких сведений нет;
        - answerInFragments — true, если во фрагментах есть ответ на вопрос целиком или на его часть, то есть отказ был ошибкой; false, если ответа во фрагментах нет.
        Ответом считаются только сведения о том самом изделии, модели или серии, о которых спрашивают: сведения о другой модели или серии,
        даже похожей, ответом не являются, и отказ в этом случае верный.
        TASK;

    protected function provider(): AIProviderInterface
    {
        return new OpenAILike(
            baseUri: config('services.llm.url'),
            key: '',
            model: config('services.llm.model'),
            // Судья рассуждает перед вердиктом (на стенде рассуждения выключены по умолчанию): без этого под схемой
            // модель оставляет обоснование пустым и решает наугад; vLLM накладывает схему только на ответ после рассуждения
            parameters: ['temperature' => 0, 'chat_template_kwargs' => ['enable_thinking' => true]],
            httpClient: TraceHttpRequests::neuronClient(),
        );
    }

    protected function instructions(): string
    {
        return <<<'PROMPT'
            Ты — строгий эксперт, оценивающий ассистента базы знаний сервисной документации по технике.
            Ассистент должен отвечать только по фрагментам документов, которые ему дали. Собственные знания ему запрещены.
            Тебе дают вопрос пользователя, фрагменты документов, которые получил ассистент, и его ответ.
            Оценивай только по этим фрагментам: то, чего во фрагментах нет, считается не подтверждённым, даже если это правда.
            Метки вида [ФИО 1], [ТЕЛЕФОН 1] — замаскированные персональные данные; их появление в ответе ошибкой не считается.
            Сведения о другой модели или серии изделия, выданные за сведения о модели из вопроса, — утверждение без опоры.
            PROMPT;
    }
}
